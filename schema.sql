CREATE TABLE IF NOT EXISTS stamps (h TEXT PRIMARY KEY, t TEXT NOT NULL, batch INTEGER);
CREATE INDEX IF NOT EXISTS stamps_batch ON stamps(batch);
CREATE TABLE IF NOT EXISTS batches (id INTEGER PRIMARY KEY AUTOINCREMENT, created TEXT NOT NULL, status TEXT NOT NULL, n INTEGER, root TEXT, nonce TEXT, digest TEXT, cals TEXT, height INTEGER, anchored TEXT);
CREATE INDEX IF NOT EXISTS stamps_t ON stamps(t);
